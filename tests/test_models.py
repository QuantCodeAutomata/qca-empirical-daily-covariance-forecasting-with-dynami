def test_harq_negative_theta1q():
    """OLS recovers negative theta_1Q from data generated by the true HARQ model.

    Simulate T observations directly from the HARQ DGP with a known negative
    attenuation coefficient, then verify that element-wise OLS recovers the
    correct sign on average across the K vech elements.
    """
    rng = np.random.default_rng(21)
    N = 3
    K = N * (N + 1) // 2
    T = 1500

    # Known true params — theta_1Q is negative (attenuation)
    true_c        =  0.02
    true_theta1q  = -0.25   # coefficient on pi_t * s_{d,t}
    true_beta_d   =  0.65
    true_beta_w   =  0.20
    true_beta_m   =  0.10

    # Independent noise proxy, uniform in [0.5, 2.0]
    Pi_array = rng.uniform(0.5, 2.0, (T, K))

    # Simulate S_t from the true HARQ DGP
    S_array = np.zeros((T, K))
    S_array[:22] = rng.uniform(0.05, 0.30, (22, K))   # burn-in period
    for t in range(22, T - 1):
        s_d = S_array[t]
        s_w = S_array[t - 4 : t + 1].mean(axis=0)
        s_m = S_array[t - 21 : t + 1].mean(axis=0)
        S_array[t + 1] = np.maximum(
            true_c
            + true_theta1q * Pi_array[t] * s_d
            + true_beta_d * s_d
            + true_beta_w * s_w
            + true_beta_m * s_m
            + rng.normal(0, 0.01, K),
            0.001,
        )

    params = fit_harq_ols(S_array, Pi_array)
    # Column index 1 is theta_1Q (noise-attenuation on daily lag)
    theta_1q = params[:, 1]   # shape (K,)
    assert theta_1q.mean() < 0, \
        f"Mean theta_1Q should be negative, got {theta_1q.mean():.4f}"


