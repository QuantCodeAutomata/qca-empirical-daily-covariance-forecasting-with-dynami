def _make_return_series(N, T, seed):
    rng = np.random.default_rng(seed)
    A = rng.standard_normal((N, N))
    true_cov = A @ A.T / N + np.eye(N) * 0.5
    L = np.linalg.cholesky(true_cov)
    return rng.standard_normal((T, N)) @ L.T * 0.01


def test_ewma_forecast_shape():
    N = 4
    returns = _make_return_series(N, 200, seed=40)
    model = EWMAModel(N=N)
    model.fit(returns)
    H = model.predict()
    assert H.shape == (N, N), f"Expected ({N},{N}), got {H.shape}"


