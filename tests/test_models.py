# ---------------------------------------------------------------------------
# DRD decomposition:  S = D @ R @ D
# ---------------------------------------------------------------------------

def test_drd_decompose_compose_roundtrip():
    rng = np.random.default_rng(30)
    N = 4
    A = rng.standard_normal((N, N))
    S = A @ A.T + np.eye(N)
    D, R = drd_decompose(S)
    S_hat = drd_compose(D, R)
    assert np.allclose(S, S_hat, atol=1e-10), \
        "DRD roundtrip must reconstruct the original matrix"


def test_drd_decompose_d_diagonal():
    rng = np.random.default_rng(31)
    N = 3
    A = rng.standard_normal((N, N))
    S = A @ A.T + np.eye(N)
    D, R = drd_decompose(S)
    off_diag = D - np.diag(np.diag(D))
    assert np.allclose(off_diag, 0), "D must be a diagonal matrix"


def test_drd_decompose_r_unit_diagonal():
    rng = np.random.default_rng(32)
    N = 4
    A = rng.standard_normal((N, N))
    S = A @ A.T + np.eye(N)
    D, R = drd_decompose(S)
    assert np.allclose(np.diag(R), 1.0, atol=1e-10), \
        "Correlation matrix R must have unit diagonal"


def test_drd_compose_is_pd():
    rng = np.random.default_rng(33)
    N = 3
    A = rng.standard_normal((N, N))
    S = A @ A.T + np.eye(N)
    D, R = drd_decompose(S)
    S_hat = drd_compose(D, R)
    eigvals = np.linalg.eigvalsh(S_hat)
    assert np.all(eigvals > 0), "drd_compose must produce a positive-definite matrix"


