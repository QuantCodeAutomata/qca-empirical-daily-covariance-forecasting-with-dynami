def _make_rcov_series(N, T, seed):
    """Return (T, K) array of vech'd realized covariances and (T, N, N) array."""
    rng = np.random.default_rng(seed)
    K = N * (N + 1) // 2
    mats = []
    vechs = []
    for _ in range(T):
        A = rng.standard_normal((N, N))
        S = A @ A.T / N + np.eye(N) * 0.1
        mats.append(S)
        vechs.append(vech(S))
    return np.array(vechs), np.array(mats)   # (T, K), (T, N, N)


def _make_pi_series(S_array, N, seed):
    """Return (T, K) array of noise-proxy vech for HARQ."""
    rng = np.random.default_rng(seed + 1000)
    T, K = S_array.shape
    # pi ~ Uniform(0.5, 2) * diag-normalised element — positive values
    pi = rng.uniform(0.5, 2.0, (T, K))
    return pi


